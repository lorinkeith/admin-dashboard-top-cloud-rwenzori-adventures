import { readFile, writeFile } from 'node:fs/promises'

const root = new URL('../supabase/', import.meta.url)
const files = ['01_schema.sql', '02_security_policies.sql', '03_storage.sql', '04_functions_triggers.sql', '05_initial_content.sql']
const sections = await Promise.all(files.map(async name => {
  const sql = await readFile(new URL(`setup/${name}`, root), 'utf8')
  return `-- SOURCE: setup/${name}\n${sql.replace(/^begin;\s*$/gim, '').replace(/^commit;\s*$/gim, '').trim()}`
}))
await writeFile(new URL('RUN_THIS_SETUP.sql', root), `-- Generated by npm run supabase:bundle. Edit the numbered sources, then regenerate.\n-- Run in your Top Cloud project's SQL Editor. Fresh or compatible schema only.\n-- Includes schema, RLS, Storage, RPCs and initial homepage. No Auth users or sample tours.\nbegin;\n\n${sections.join('\n\n')}\n\ncommit;\n`)
console.log('Created supabase/RUN_THIS_SETUP.sql from setup files 01–05 (one transaction).')
